"""Scaffolding: create the on-disk skeleton of a new skill package."""

from __future__ import annotations

from pathlib import Path
from textwrap import dedent

from skillsmith.models import NAME_PATTERN, SkillManifest

SKILL_MD_TEMPLATE = dedent(
    """\
    ---
    name: {name}
    description: {description}
    version: 0.1.0
    license: MIT
    tags:
      - starter
    ---

    # {title}

    Describe what this skill does and when an agent should use it.

    ## When to use

    - ...

    ## Instructions

    1. ...
    2. ...

    ## Notes

    - Keep this skill focused on a single capability.
    """
)

RUNNER_TEMPLATE = dedent(
    """\
    #!/usr/bin/env python3
    \"\"\"Example entry script for the {name} skill.

    Replace this placeholder with real automation logic. Keep scripts
    executable and self-contained.
    \"\"\"

    import argparse
    import sys


    def main() -> int:
        parser = argparse.ArgumentParser(description="{name} runner")
        parser.add_argument("input", nargs="?", default="-", help="input path or '-' for stdin")
        args = parser.parse_args()
        print(f"{name} received: {{args.input}}", file=sys.stderr)
        return 0


    if __name__ == "__main__":
        sys.exit(main())
    """
)

README_TEMPLATE = dedent(
    """\
    # {title}

    {description}

    Generated by SkillSmith. Fill in the sections below before publishing.

    ## Install

    ```bash
    skillsmith install dist/{name}-0.1.0.skill --target ~/.agents/skills
    ```
    """
)


class Scaffold:
    """Create a new skill directory from a built-in template."""

    def new_skill(
        self,
        base_dir: Path,
        name: str,
        description: str = "",
        version: str = "0.1.0",
        license_id: str = "MIT",
    ) -> Path:
        """Create ``base_dir/name`` with SKILL.md, scripts/, references/.

        Returns the created skill directory. Raises ValueError on invalid
        names or if the target directory already exists.
        """
        if not NAME_PATTERN.match(name):
            raise ValueError(
                f"invalid skill name {name!r}: use lowercase kebab-case "
                "(letters, digits, hyphens; 2-64 chars)"
            )
        skill_dir = base_dir / name
        if skill_dir.exists():
            raise ValueError(f"target already exists: {skill_dir}")

        manifest = SkillManifest(
            name=name,
            description=description or f"TODO: describe the {name} skill",
            version=version,
            license=license_id,
            source_path=skill_dir,
        )

        (skill_dir / "scripts").mkdir(parents=True)
        (skill_dir / "references").mkdir()

        (skill_dir / "SKILL.md").write_text(
            SKILL_MD_TEMPLATE.format(
                name=manifest.name,
                description=manifest.description,
                title=manifest.name.replace("-", " ").title(),
            ),
            encoding="utf-8",
        )
        runner = skill_dir / "scripts" / "run.py"
        runner.write_text(
            RUNNER_TEMPLATE.format(name=manifest.name), encoding="utf-8"
        )
        runner.chmod(0o755)
        (skill_dir / "README.md").write_text(
            README_TEMPLATE.format(
                name=manifest.name,
                description=manifest.description,
                title=manifest.name.replace("-", " ").title(),
            ),
            encoding="utf-8",
        )
        return skill_dir
